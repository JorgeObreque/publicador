/**
 * Helpers puros sobre `REGIONS` y `COMMUNES`. No leen ni escriben en
 * Prisma; el `TerritoryService` los envuelve para servir el catálogo vía
 * HTTP. Mantenerlos libres de dependencias facilita su uso en tests
 * unitarios y en el cliente web (que importa los tipos desde el módulo).
 */

const normalize = (value: string): string =>
  value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim();

export function findRegion(cut: string): Region | undefined {
  return REGIONS.find((r) => r.cutCode === cut);
}

export function findCommune(cut: string): Commune | undefined {
  return COMMUNES.find((c) => c.cutCode === cut);
}

export function communesByRegion(regionCut: string): readonly Commune[] {
  return COMMUNES.filter((c) => c.regionCutCode === regionCut);
}

export function regionByCommune(communeCut: string): Region | undefined {
  const commune = findCommune(communeCut);
  if (!commune) return undefined;
  return findRegion(commune.regionCutCode);
}

/**
 * Búsqueda parcial, insensible a mayúsculas/acentos, sobre el nombre de
 * la comuna. Si se entrega `regionCut`, filtra adicionalmente por región.
 * Devuelve hasta `limit` resultados ordenados por nombre alfabético.
 */
export function searchCommunes(
  query: string,
  regionCut?: string,
  limit = 25,
): readonly Commune[] {
  const needle = normalize(query);
  if (needle.length === 0) return [];
  const pool = regionCut
    ? COMMUNES.filter((c) => c.regionCutCode === regionCut)
    : COMMUNES;
  const matches = pool.filter((c) => normalize(c.name).includes(needle));
  matches.sort((a, b) => a.name.localeCompare(b.name, 'es'));
  return matches.slice(0, limit);
}
